export type BarLocalErrorCode = (typeof BAR_LOCAL_ERROR_CODES)[keyof typeof BAR_LOCAL_ERROR_CODES] | 'ACCOUNT_LOCKED' | 'DUPLICATE_RECORD' | 'SETUP_LOCAL_ONLY' | 'SETUP_UNAVAILABLE' | 'SETUP_SECRET_INVALID' | 'RATE_LIMITED'

export const RETRYABLE_CODES: ReadonlySet<string> = Object.freeze(new Set<string>([
  BAR_LOCAL_ERROR_CODES.OPERATION_EXECUTING,
  BAR_LOCAL_ERROR_CODES.SERVICE_UNAVAILABLE,
  BAR_LOCAL_ERROR_CODES.DATABASE_UNAVAILABLE,
  BAR_LOCAL_ERROR_CODES.UNKNOWN_OUTCOME,
  BAR_LOCAL_ERROR_CODES.INTERNAL_ERROR
]))

export interface BarLocalErrorOptions {
  retrySameOperation?: boolean
  requiresManager?: boolean
  details?: unknown
  httpStatus?: number
  cause?: unknown
}

export interface BarLocalErrorResponse {
  ok: false
  outcome: 'executing' | 'refused'
  code: string
  message: string
  retry_same_operation: boolean
  requires_manager: boolean
  details: unknown
  correlation_id: string
}

export class BarLocalError extends Error {
  readonly code: BarLocalErrorCode
  readonly retrySameOperation: boolean
  readonly requiresManager: boolean
  readonly details: unknown
  readonly httpStatus: number

  constructor(code: BarLocalErrorCode, message: string, options: BarLocalErrorOptions = {}) {
    super(message, options.cause ? { cause: options.cause } : undefined)
    this.name = 'BarLocalError'
    this.code = code
    this.retrySameOperation = options.retrySameOperation ?? RETRYABLE_CODES.has(code)
    this.requiresManager = options.requiresManager ?? false
    this.details = options.details ?? null
    this.httpStatus = options.httpStatus ?? (code === BAR_LOCAL_ERROR_CODES.AUTH_REQUIRED ? 401 : 400)
  }

  toResponse(correlationId: string): BarLocalErrorResponse {
    return {
      ok: false,
      outcome: this.code === BAR_LOCAL_ERROR_CODES.OPERATION_EXECUTING ? 'executing' : 'refused',
      code: this.code,
      message: this.message,
      retry_same_operation: this.retrySameOperation,
      requires_manager: this.requiresManager,
      details: this.details,
      correlation_id: correlationId
    }
  }
}

export function asBarLocalError(
  error: unknown,
  fallbackCode: BarLocalErrorCode = BAR_LOCAL_ERROR_CODES.INTERNAL_ERROR,
  fallbackMessage = 'The local Bar service could not complete the operation.'
): BarLocalError {
  if (error instanceof BarLocalError) return error
  const candidate = typeof error === 'object' && error !== null && 'code' in error && typeof error.code === 'string'
    ? error.code
    : null
  const code = candidate && (Object.values(BAR_LOCAL_ERROR_CODES) as string[]).includes(candidate)
    ? (candidate as BarLocalErrorCode)
    : fallbackCode
  const message = error instanceof Error ? error.message : fallbackMessage
  return new BarLocalError(code, message || fallbackMessage, { cause: error })
}
