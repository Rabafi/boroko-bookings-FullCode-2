import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'

const root = new URL('..', import.meta.url)
const read = (path) => fs.readFileSync(new URL(path, root), 'utf8')

test('deferred Bar migration is transactional and fail-closed for immutable proof evidence', () => {
  const sql = read('supabase/migrations/20260820140000_bar_base_deferred_service_tranche.sql')
  assert.match(sql, /^begin;/m)
  assert.match(sql, /commit;\s*$/m)
  assert.match(sql, /public\.pos_cashup_proof_storage_access\(name, true\)/)
  assert.match(sql, /public\.pos_cashup_proof_storage_access\(name, false\)/)
  assert.doesNotMatch(sql, /create policy private_cashup_proofs_delete/i)
  assert.match(sql, /on delete restrict/i)
  assert.match(sql, /prevent_pos_cashup_proof_mutation/)
  assert.match(sql, /v_row\.status <> 'submitted'/)
  assert.match(sql, /metadata->>'mimetype'/)
  assert.match(sql, /sha256.*\{64\}/i)
})

