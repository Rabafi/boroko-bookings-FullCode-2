test('cash-up proof uses the session-bound Storage client and fails closed without deployed app context', () => {
  const auth = read('src/main/domains/authClients.js')
  const domain = read('src/main/domains/pos.js')
  const main = read('src/main/index.js')
  const close = read('src/renderer/src/components/hospitality-pos/HposCashClose.jsx')
  const proofs = read('src/renderer/src/components/hospitality-pos/HposCashupProofs.jsx')
  const myCashup = read('src/renderer/src/components/hospitality-pos/HposMyCashup.jsx')
  const migration = read('supabase/migrations/20260820140000_bar_base_deferred_service_tranche.sql')
  const supabaseClient = read('node_modules/@supabase/supabase-js/src/SupabaseClient.ts')
  const storageClient = read('node_modules/@supabase/storage-js/src/StorageClient.ts')

  assert.match(auth, /global:\s*\{\s*headers: token \? \{ 'x-boroko-session': token \} : \{\}\s*\}/s)
  assert.match(auth, /state\.supabase = buildSupabaseClient\(SUPABASE_ANON_KEY, state\.backendSession\?\.token \|\| null\)/)
  assert.match(supabaseClient, /this\.storage = new SupabaseStorageClient\([\s\S]*this\.headers,[\s\S]*this\.fetch/)
  assert.match(storageClient, /return new StorageFileApi\(this\.url, this\.headers, id, this\.fetch\)/)
  assert.match(domain, /state\.supabase\.storage\.from\('private-cashup-proofs'\)/)
  assert.match(main, /pos:attachCashupProof[\s\S]*requireCapability\('pos\.view'\)/)
  assert.match(domain, /proof metadata requires a live authorized connection/)
  assert.doesNotMatch(domain, /file_base64|local_path|\.remove\(/)
  assert.match(proofs, /file\.arrayBuffer\(\)/)
  assert.match(proofs, /crypto\.subtle\.digest\('SHA-256'/)
  assert.match(proofs, /localStorage\.(getItem|setItem)/)
  assert.match(proofs, /attachCashupProof/)
  assert.match(proofs, /getCashupProofAttachments/)
  assert.match(proofs, /createCashupProofSignedUrl/)
  assert.match(close, /HposCashupProofs/)
  assert.match(myCashup, /HposCashupProofs/)
  assert.match(migration, /if v_lodge is distinct from public\.app_current_lodge_id\(\) then return false/)
  assert.match(migration, /exception when others then\s*return false/)
  assert.match(close, /deployed Storage policy is unavailable/)
  assert.doesNotMatch(proofs, /file_base64|local_path|createObjectURL|data:/i)
})
