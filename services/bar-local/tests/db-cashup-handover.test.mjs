import test from 'node:test'
import assert from 'node:assert/strict'
import { createHarness, sha256Json, sha256Text } from './harness.mjs'

test('blind local handover closes and submits atomically, replays once, and corrects only a rejected count', async (t) => {
  const h = await createHarness(t)
  const shiftId = await h.openShift('100.00')
  const mine = await h.query('cashup.mine')
  assert.equal(mine.data.shift.id, shiftId)
  assert.equal(mine.data.submission, null)
  assert.doesNotMatch(JSON.stringify(mine.data), /expected_cash|variance|cash_sales|card_sales/)
  const generalShift = await h.query('shift.current')
  assert.equal(generalShift.data.shift_id, shiftId)
  assert.doesNotMatch(JSON.stringify(generalShift.data), /expected_cash|counted_cash|variance|counted_card/)
  const stale = await h.call('cmd_cashup_handover', h.envelope('cashup.handover', {
    shift_id: shiftId, expected_shift_version: 2, counted_cash: '95.00'
  }))
  assert.equal(stale.error.code, 'SHIFT_VERSION_CONFLICT')
  assert.equal((await h.query('cashup.mine')).data.shift.status, 'open')
  const env = h.envelope('cashup.handover', { shift_id: shiftId, expected_shift_version: 1, counted_cash: '95.00', notes: 'First count' })
  const submitted = await h.call('cmd_cashup_handover', env)
  assert.equal(submitted.ok, true, JSON.stringify(submitted.error))
  assert.equal(submitted.result.status, 'submitted')
  assert.equal(submitted.result.shift_version, 2)
  assert.equal(Object.hasOwn(submitted.result, 'expected_cash'), false)
  assert.equal(Object.hasOwn(submitted.result, 'variance'), false)
  const replay = await h.call('cmd_cashup_handover', env)
  assert.equal(replay.replayed, true)
  assert.deepEqual(replay.receipt, submitted.receipt)
  await assert.rejects(h.call('cmd_cashup_handover', { ...env, payload: { ...env.payload, counted_cash: '96.00' } }), /different content|different payload|idempotency/i)
  const stored = await h.migrator.query('SELECT s.status,c.counted_cash,c.expected_cash,c.variance FROM bar_local.shifts s JOIN bar_local.cashups c ON c.shift_id=s.id WHERE s.id=$1', [shiftId])
  assert.equal(stored.rows[0].status, 'closed')
  assert.equal(stored.rows[0].counted_cash, '95.00')
  assert.equal(stored.rows[0].expected_cash, '100.00')
  assert.equal(stored.rows[0].variance, '-5.00')
  assert.equal((await h.migrator.query('SELECT count(*)::integer AS count FROM bar_local.cashups WHERE shift_id=$1', [shiftId])).rows[0].count, 1)
  const duplicate = await h.call('cmd_cashup_handover', h.envelope('cashup.handover', { shift_id: shiftId, expected_shift_version: 2, counted_cash: '100.00' }))
  assert.equal(duplicate.error.code, 'CASHUP_ALREADY_REVIEWED')

  const review = h.envelope('cashup.review', { cashup_id: submitted.result.cashup_id, decision: 'rejected', reason: 'Recount drawer' })
  const hash = sha256Json(review.payload)
  review.payload.approval_id = await h.approve('pos.cashup', hash, { approverStaffId: h.ownerStaffId })
  const rejected = await h.call('cmd_cashup_review', review, { approvalHash: hash, tokenHash: h.managerTokenHash })
  assert.equal(rejected.ok, true, JSON.stringify(rejected.error))
  const returned = await h.query('cashup.mine')
  assert.equal(returned.data.submission.review_notes, 'Recount drawer')
  assert.doesNotMatch(JSON.stringify(returned.data), /expected_cash|variance/)
  const correction = await h.call('cmd_cashup_handover', h.envelope('cashup.handover', { shift_id: shiftId, expected_shift_version: 2, counted_cash: '100.00', notes: 'Recounted' }))
  assert.equal(correction.ok, true, JSON.stringify(correction.error))
  assert.equal(correction.result.cashup_id, submitted.result.cashup_id)
  assert.equal(correction.result.shift_version, 3)
  const audit = await h.migrator.query("SELECT before FROM bar_local.audit_log WHERE action='cashup.submitted' AND operation_id<>$1 ORDER BY created_at DESC LIMIT 1", [env.operation_id])
  assert.equal(audit.rows[0].before.cashup.status, 'rejected')
  assert.equal(Number(audit.rows[0].before.cashup.counted_cash), 95)
})

test('handover refuses another operator and open tabs without closing or submitting anything', async (t) => {
  const h = await createHarness(t)
  const shiftId = await h.openShift()
  const foreign = await h.call('cmd_cashup_handover', h.envelope('cashup.handover', { shift_id: shiftId, expected_shift_version: 1, counted_cash: '100.00' }), { tokenHash: h.managerTokenHash })
  assert.equal(foreign.error.code, 'SHIFT_SCOPE_MISMATCH')
  assert.equal((await h.query('cashup.mine', {}, { tokenHash: h.managerTokenHash })).data.shift, null)
  const tab = await h.call('cmd_tab_open', h.envelope('tab.open', { table_label: 'Unpaid check' }))
  assert.equal(tab.ok, true)
  const blocked = await h.call('cmd_cashup_handover', h.envelope('cashup.handover', { shift_id: shiftId, expected_shift_version: 1, counted_cash: '100.00' }))
  assert.equal(blocked.error.code, 'TAB_NOT_OPEN')
  const mine = await h.query('cashup.mine')
  assert.equal(mine.data.shift.status, 'open')
  assert.equal(mine.data.shift.version, 1)
  assert.equal(mine.data.submission, null)
  const staffId = await h.insertStaff('Cashier', 'cashier', ['pos.view', 'pos.cashup'])
  const token = sha256Text('cashier-pending-review')
  await h.runtime.query('SELECT bar_local.service_create_session($1,$2,$3,$4)', [staffId, h.deviceId, h.outletId, token])
  await assert.rejects(h.query('cashup.pending', {}, { tokenHash: token }), /authorised owner or manager/)
  const summary = await h.query('cashup.summary', { shift_id: shiftId }, { tokenHash: token })
  assert.doesNotMatch(JSON.stringify(summary.data), /expected_cash|cash_sales|card_sales|cash_movements|cashup/)
})

test('concurrent counts on one shift produce one handover and one stale-version refusal', async (t) => {
  const h = await createHarness(t)
  const shiftId = await h.openShift()
  const a = await h.newRuntimeClient()
  const b = await h.newRuntimeClient()
  const results = await Promise.all([
    h.callWith(a, 'cmd_cashup_handover', h.envelope('cashup.handover', { shift_id: shiftId, expected_shift_version: 1, counted_cash: '100.00' })),
    h.callWith(b, 'cmd_cashup_handover', h.envelope('cashup.handover', { shift_id: shiftId, expected_shift_version: 1, counted_cash: '99.00' }))
  ])
  assert.equal(results.filter((result) => result.ok).length, 1)
  assert.equal(results.find((result) => !result.ok).error.code, 'SHIFT_VERSION_CONFLICT')
  assert.equal((await h.migrator.query('SELECT count(*)::integer AS count FROM bar_local.cashups WHERE shift_id=$1', [shiftId])).rows[0].count, 1)
})
