const RETRYABLE_DATABASE_CODES = new Set<string>(['40001', '40P01', '57014', '57P01', '57P02', '57P03'])

export function httpStatusForCode(code: string): number {
  if (code === 'ACCOUNT_LOCKED') return 429
  if (UNAUTHORIZED.has(code)) return 401
  if (FORBIDDEN.has(code)) return 403
  if (NOT_FOUND.has(code)) return 404
  if (CONFLICT.has(code) || code === 'DUPLICATE_RECORD') return 409
  if (UNAVAILABLE.has(code)) return 503
  if (code === BAR_LOCAL_ERROR_CODES.INTERNAL_ERROR) return 500
  return 400
}

interface DatabaseFailure {
  code?: unknown
  detail?: unknown
  message?: unknown
}

export function mapDatabaseError(error: unknown): BarLocalError {
  if (error instanceof BarLocalError) return error
  const failure = typeof error === 'object' && error !== null ? error as DatabaseFailure : {}
  const pgCode = typeof failure.code === 'string' ? failure.code : null
  if (pgCode === 'BL001') {
    const code = typeof failure.detail === 'string' && failure.detail ? failure.detail : BAR_LOCAL_ERROR_CODES.VALIDATION_FAILED
    const message = typeof failure.message === 'string' && failure.message ? failure.message : 'The local authority refused the operation.'
    return new BarLocalError(code as BarLocalErrorCode, message, {
      httpStatus: httpStatusForCode(code),
      retrySameOperation: code === BAR_LOCAL_ERROR_CODES.OPERATION_EXECUTING
    })
  }
  if (pgCode && RETRYABLE_DATABASE_CODES.has(pgCode)) {
    return new BarLocalError(BAR_LOCAL_ERROR_CODES.SERVICE_UNAVAILABLE, 'The local database is busy or unavailable. Retry with the same operation identifier.', {
      retrySameOperation: true,
      httpStatus: 503,
      cause: error
    })
  }
  if (pgCode === '23505') {
    return new BarLocalError('DUPLICATE_RECORD', 'A record with this identity already exists.', { httpStatus: 409, cause: error })
  }
  if (pgCode === '23503' || pgCode === '23514' || pgCode === '22P02' || pgCode === '22007' || pgCode === '22008') {
    return new BarLocalError(BAR_LOCAL_ERROR_CODES.VALIDATION_FAILED, 'The local authority could not validate the supplied reference or value.', { cause: error })
  }
  if (pgCode === '42501') {
    return new BarLocalError(BAR_LOCAL_ERROR_CODES.INTERNAL_ERROR, 'The local database privilege boundary rejected the operation.', { httpStatus: 500, cause: error })
  }
  return new BarLocalError(BAR_LOCAL_ERROR_CODES.INTERNAL_ERROR, 'The local Bar database could not complete the operation.', { httpStatus: 500, cause: error })
}
